-- PostgreSQL schema for the raw-SQL application repositories.
-- The command runner executes each block separated by this marker.

-- django:statement
CREATE TABLE IF NOT EXISTS staff (
    staff_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password VARCHAR(128) NOT NULL,
    last_login TIMESTAMPTZ,
    is_superuser BOOLEAN NOT NULL DEFAULT FALSE,
    username VARCHAR(150) NOT NULL UNIQUE,
    first_name VARCHAR(150) NOT NULL DEFAULT '',
    last_name VARCHAR(150) NOT NULL DEFAULT '',
    email VARCHAR(254) NOT NULL DEFAULT '',
    is_staff BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    date_joined TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    role VARCHAR(30) NOT NULL DEFAULT 'wait_staff'
        CHECK (role IN ('cashier', 'kitchen', 'wait_staff', 'manager'))
)

-- django:statement
CREATE TABLE IF NOT EXISTS tables (
    table_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    free_status BOOLEAN NOT NULL DEFAULT TRUE
)

-- django:statement
CREATE TABLE IF NOT EXISTS customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id INTEGER REFERENCES tables(table_id) ON DELETE SET NULL,
    session_token CHAR(36) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)

-- django:statement
CREATE TABLE IF NOT EXISTS menu_items (
    menu_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR(100) NOT NULL,
    description TEXT,
    price DECIMAL(10, 2) NOT NULL CHECK (price > 0),
    availability_status BOOLEAN NOT NULL DEFAULT TRUE
)

-- django:statement
CREATE TABLE IF NOT EXISTS orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(customer_id) ON DELETE RESTRICT,
    table_id INTEGER NOT NULL REFERENCES tables(table_id) ON DELETE RESTRICT,
    staff_id INTEGER REFERENCES staff(staff_id) ON DELETE SET NULL,
    order_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (order_status IN ('pending','confirmed','preparing','ready','served','cancelled')),
    order_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)

-- django:statement
CREATE INDEX IF NOT EXISTS orders_order_time_idx ON orders(order_time)

-- django:statement
CREATE INDEX IF NOT EXISTS orders_order_status_idx ON orders(order_status)

-- django:statement
CREATE TABLE IF NOT EXISTS order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    menu_item_id INTEGER NOT NULL REFERENCES menu_items(menu_item_id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    item_subtotal DECIMAL(10, 2) NOT NULL DEFAULT 0,
    special_instructions VARCHAR(255)
)

-- django:statement
CREATE OR REPLACE FUNCTION set_order_item_subtotal()
RETURNS TRIGGER AS $$
BEGIN
    SELECT NEW.quantity * price
      INTO NEW.item_subtotal
      FROM menu_items
     WHERE menu_item_id = NEW.menu_item_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql

-- django:statement
DROP TRIGGER IF EXISTS order_items_subtotal_before_write ON order_items

-- django:statement
CREATE TRIGGER order_items_subtotal_before_write
BEFORE INSERT OR UPDATE OF quantity, menu_item_id ON order_items
FOR EACH ROW
EXECUTE FUNCTION set_order_item_subtotal()

-- django:statement
CREATE TABLE IF NOT EXISTS payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    amount DECIMAL(10, 2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('Cash', 'Mobile Money')),
    cashier_id INTEGER NOT NULL REFERENCES staff(staff_id) ON DELETE RESTRICT,
    transaction_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)

-- django:statement
CREATE TABLE IF NOT EXISTS sales_record (
    sales_record_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    payment_id INTEGER NOT NULL UNIQUE REFERENCES payments(payment_id) ON DELETE RESTRICT,
    total_amount DECIMAL(10, 2) NOT NULL,
    sale_date DATE NOT NULL DEFAULT CURRENT_DATE
)
-- django:statement
CREATE OR REPLACE FUNCTION occupy_table_on_order()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE tables SET free_status = FALSE WHERE table_id = NEW.table_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql

-- django:statement
DROP TRIGGER IF EXISTS orders_occupy_table_after_insert ON orders

-- django:statement
CREATE TRIGGER orders_occupy_table_after_insert
AFTER INSERT ON orders
FOR EACH ROW
EXECUTE FUNCTION occupy_table_on_order()

-- django:statement
CREATE OR REPLACE FUNCTION handle_payment()
RETURNS TRIGGER AS $$
DECLARE
    v_table_id INTEGER;
BEGIN
    INSERT INTO sales_record (order_id, payment_id, total_amount, sale_date)
    VALUES (NEW.order_id, NEW.payment_id, NEW.amount,
            (NEW.transaction_time AT TIME ZONE 'Africa/Kampala')::date);

    SELECT table_id INTO v_table_id FROM orders WHERE order_id = NEW.order_id;

    -- only free the table if nothing unpaid is left on it
    UPDATE tables t SET free_status = TRUE
     WHERE t.table_id = v_table_id
       AND NOT EXISTS (
            SELECT 1 FROM orders o
             WHERE o.table_id = t.table_id
               AND o.order_status <> 'cancelled'
               AND NOT EXISTS (SELECT 1 FROM payments p WHERE p.order_id = o.order_id));
    RETURN NEW;
END;
$$ LANGUAGE plpgsql

-- django:statement
DROP TRIGGER IF EXISTS payments_after_insert ON payments

-- django:statement
CREATE TRIGGER payments_after_insert
AFTER INSERT ON payments
FOR EACH ROW
EXECUTE FUNCTION handle_payment()

-- django:statement
CREATE OR REPLACE FUNCTION free_table_on_cancel()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE tables t SET free_status = TRUE
     WHERE t.table_id = NEW.table_id
       AND NOT EXISTS (
            SELECT 1 FROM orders o
             WHERE o.table_id = t.table_id
               AND o.order_status <> 'cancelled'
               AND NOT EXISTS (SELECT 1 FROM payments p WHERE p.order_id = o.order_id));
    RETURN NEW;
END;
$$ LANGUAGE plpgsql

-- django:statement
DROP TRIGGER IF EXISTS orders_free_table_after_cancel ON orders

-- django:statement
CREATE TRIGGER orders_free_table_after_cancel
AFTER UPDATE OF order_status ON orders
FOR EACH ROW
WHEN (NEW.order_status = 'cancelled' AND OLD.order_status <> 'cancelled')
EXECUTE FUNCTION free_table_on_cancel()

